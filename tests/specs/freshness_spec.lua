-- Unit tests for pfm-inventory/server/freshness.lua under a controlled clock.
Config = {}
load_resource('pfm-inventory/config/freshness.lua')
load_resource('pfm-inventory/server/freshness.lua')
local F = PFFreshness

local HOUR, DAY = 3600, 86400
local NOW = 1700000000

BeforeEach = function()
    F.StorageOverrides = {}
    Config.Freshness.Enabled = true
end

describe('classification', function()
    it('knows perishables and leaves everything else alone', function()
        assert_true(F.IsPerishable('sandwich'))
        assert_true(F.IsPerishable('SANDWICH'), 'case-insensitive')
        assert_false(F.IsPerishable('lockpick'))
        assert_false(F.IsPerishable(nil))
    end)
    it('treats everything as non-perishable when disabled', function()
        Config.Freshness.Enabled = false
        assert_false(F.IsPerishable('sandwich'))
    end)
end)

describe('storage resolution', function()
    it('maps identifiers to storage types', function()
        assert_eq(F.StorageFor(7), 'person', 'player source')
        assert_eq(F.StorageFor('trunk-ABC123'), 'trunk')
        assert_eq(F.StorageFor('glovebox-ABC123'), 'glovebox')
        assert_eq(F.StorageFor('drop-12'), 'outdoor')
        assert_eq(F.StorageFor('backpack-X1'), 'person')
        assert_eq(F.StorageFor('house_stash_1'), 'stash')
    end)
    it('honours runtime overrides and rejects unknown types', function()
        assert_true(F.SetStorageOverride('restaurant-fridge-1', 'fridge'))
        assert_eq(F.StorageFor('restaurant-fridge-1'), 'fridge')
        assert_false(F.SetStorageOverride('x', 'magic_preserver'), 'unknown storage type')
        assert_true(F.SetStorageOverride('restaurant-fridge-1', nil))
        assert_eq(F.StorageFor('restaurant-fridge-1'), 'stash')
    end)
end)

describe('Prepare', function()
    it('assigns a server batch and full life to new items', function()
        local info = F.Prepare('sandwich', {}, 'person', NOW)
        assert_eq(type(info.fresh.batch), 'string')
        assert_eq(info.fresh.life, 12 * HOUR)
        assert_eq(info.fresh.used, 0)
        assert_eq(info.fresh.storage, 'person')
        assert_near(F.Percent(info.fresh, NOW), 100)
    end)
    it('ignores a forged shelf life and clamps used', function()
        local info = F.Prepare('sandwich', { fresh = { batch = 'B1', life = 999999999, used = -50, at = NOW, storage = 'person' } }, 'person', NOW)
        assert_eq(info.fresh.life, 12 * HOUR, 'life comes from config')
        assert_eq(info.fresh.used, 0, 'negative used clamped')
    end)
    it('ignores a future timestamp', function()
        local info = F.Prepare('sandwich', { fresh = { batch = 'B1', used = 0, at = NOW + 10 * DAY, storage = 'person' } }, 'person', NOW)
        assert_eq(info.fresh.at, NOW)
        assert_near(F.Percent(info.fresh, NOW), 100)
    end)
    it('settles shelf life at the old storage rate before moving', function()
        local info = F.Prepare('sandwich', {}, 'fridge', NOW)
        -- 8h in the fridge at rate 0.25 = 2h of life used
        info = F.Prepare('sandwich', info, 'person', NOW + 8 * HOUR)
        assert_eq(info.fresh.used, 2 * HOUR)
        assert_eq(info.fresh.storage, 'person')
        assert_eq(info.fresh.at, NOW + 8 * HOUR)
    end)
    it('keeps the batch id across moves', function()
        local info = F.Prepare('sandwich', {}, 'stash', NOW)
        local batch = info.fresh.batch
        info = F.Prepare('sandwich', info, 'trunk', NOW + HOUR)
        assert_eq(info.fresh.batch, batch)
    end)
    it('gives each new item its own batch', function()
        local a = F.Prepare('sandwich', {}, 'stash', NOW)
        local b = F.Prepare('sandwich', {}, 'stash', NOW)
        assert_true(a.fresh.batch ~= b.fresh.batch)
    end)
    it('does nothing to non-perishables', function()
        local info = F.Prepare('lockpick', { quality = 50 }, 'person', NOW)
        assert_eq(info.fresh, nil)
        assert_eq(info.quality, 50)
    end)
end)

describe('freshness across storage conditions', function()
    local function pctAfter(storage, seconds)
        local info = F.Prepare('sandwich', {}, storage, NOW)
        return F.Percent(info.fresh, NOW + seconds)
    end
    it('normal storage uses life at rate 1', function()
        assert_near(pctAfter('stash', 6 * HOUR), 50, 0.001)
    end)
    it('refrigeration slows spoilage', function()
        assert_near(pctAfter('fridge', 6 * HOUR), 87.5, 0.001)
    end)
    it('freezing extends preservation much further', function()
        assert_near(pctAfter('freezer', 6 * HOUR), 98, 0.001)
    end)
    it('heat and sunlight accelerate spoilage', function()
        assert_true(pctAfter('hot', 2 * HOUR) < pctAfter('sunlight', 2 * HOUR))
        assert_true(pctAfter('sunlight', 2 * HOUR) < pctAfter('stash', 2 * HOUR))
    end)
    it('trunks and gloveboxes are worse than proper storage', function()
        assert_true(pctAfter('trunk', 4 * HOUR) < pctAfter('stash', 4 * HOUR))
        assert_true(pctAfter('glovebox', 4 * HOUR) < pctAfter('trunk', 4 * HOUR))
        assert_true(pctAfter('trunk', 4 * HOUR) < pctAfter('fridge', 4 * HOUR))
    end)
    it('a failed fridge is no better than the counter', function()
        assert_near(pctAfter('broken_fridge', 6 * HOUR), pctAfter('stash', 6 * HOUR), 0.001)
    end)
    it('never goes below zero', function()
        assert_eq(pctAfter('hot', 30 * DAY), 0)
    end)
end)

describe('states and effects', function()
    it('maps percentages to bands', function()
        assert_eq(F.StateFor(95).state, 'fresh')
        assert_eq(F.StateFor(50).state, 'good')
        assert_eq(F.StateFor(10).state, 'stale')
        assert_eq(F.StateFor(0).state, 'spoiled')
    end)
    it('spoiled food stays usable with reduced benefit and illness risk', function()
        local e = F.EffectsFor(0)
        assert_eq(e.state, 'spoiled')
        assert_true(e.benefit > 0 and e.benefit < 1)
        assert_true(e.illness > 0)
        assert_eq(F.EffectsFor(100).illness, 0)
    end)
end)

describe('stacking rules', function()
    it('non-perishables always stack (original behaviour)', function()
        assert_true(F.CanStack('lockpick', { a = 1 }, { b = 2 }, NOW))
    end)
    it('perishables from different batches never stack', function()
        local a = F.Prepare('sandwich', {}, 'stash', NOW)
        local b = F.Prepare('sandwich', {}, 'stash', NOW)
        assert_false(F.CanStack('sandwich', a, b, NOW))
    end)
    it('same batch with matching freshness stacks', function()
        local a = F.Prepare('sandwich', {}, 'stash', NOW)
        local b = F.CopyInfo(a)
        assert_true(F.CanStack('sandwich', a, b, NOW))
    end)
    it('same batch but diverged freshness does not stack', function()
        local a = F.Prepare('sandwich', {}, 'stash', NOW)
        local b = F.Prepare('sandwich', F.CopyInfo(a), 'hot', NOW)
        assert_false(F.CanStack('sandwich', a, b, NOW + 2 * HOUR))
    end)
    it('perishables without records never merge into tracked stacks', function()
        local a = F.Prepare('sandwich', {}, 'stash', NOW)
        assert_false(F.CanStack('sandwich', {}, a, NOW))
    end)
    it('merging keeps the worse freshness', function()
        local good = F.Prepare('sandwich', {}, 'stash', NOW)
        local worse = F.CopyInfo(good)
        worse.fresh.used = 3 * HOUR
        F.MergeInto(good.fresh, worse.fresh, NOW)
        assert_eq(good.fresh.used, 3 * HOUR)
    end)
end)

describe('legacy items and display', function()
    it('EnsureItems backfills records one batch per slot and re-anchors storage', function()
        local items = {
            [1] = { name = 'sandwich', amount = 3, slot = 1, info = {} },
            [2] = { name = 'sandwich', amount = 2, slot = 2 },
            [3] = { name = 'lockpick', amount = 1, slot = 3, info = {} },
        }
        assert_true(F.EnsureItems(items, 'fridge-1', NOW))
        assert_eq(items[1].info.fresh.storage, 'fridge', "'fridge' identifiers resolve to fridge storage")
        assert_true(items[1].info.fresh.batch ~= items[2].info.fresh.batch)
        assert_eq(items[3].info.fresh, nil)
        assert_false(F.EnsureItems(items, 'fridge-1', NOW), 'second pass is a no-op')
    end)
    it('DecorateForClient copies, never mutates stored items', function()
        local items = { [1] = { name = 'sandwich', amount = 1, slot = 1, info = F.Prepare('sandwich', {}, 'stash', NOW) } }
        local out = F.DecorateForClient(items, NOW + 6 * HOUR)
        assert_eq(out[1].info.freshDisplay.pct, 50)
        assert_eq(out[1].info.freshDisplay.state, 'good')
        assert_eq(items[1].info.freshDisplay, nil, 'stored item untouched')
    end)
end)
